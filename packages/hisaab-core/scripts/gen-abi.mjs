import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "../../contracts/out");
const read = (name) => JSON.parse(readFileSync(join(out, `${name}.sol`, `${name}.json`), "utf8")).abi;

const body = [
  `export const registryAbi = ${JSON.stringify(read("HisaabRegistry"), null, 2)} as const;`,
  `export const receiptAbi = ${JSON.stringify(read("HisaabReceipt"), null, 2)} as const;`,
  "",
].join("\n\n");
writeFileSync(join(root, "src/abi.ts"), `// Generated by scripts/gen-abi.mjs from contracts/out. Do not edit.\n\n${body}`);
console.log("wrote src/abi.ts");
